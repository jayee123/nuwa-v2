export function isW2Day(day: number): boolean {
  return day >= 8 && day <= 14
}

export function buildDayLockBloc(day: number, theme: string): string {
  return `
🔒 今天鎖定：Day ${day}（${theme}）
- 禁止帶入 Day ${day + 1} 或未來任何 Day 的課程內容
- 禁止提前教未來天數的技巧
- 如果學員問未來內容，回答「這個很好的問題，到了那一天我們會好好練習」
`
}
